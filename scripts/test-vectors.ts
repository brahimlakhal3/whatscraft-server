/**
 * Cross-implementation test vectors.
 *
 * Generates a fixed set of identities and a message sealed by *this* reference
 * implementation, then writes them to app/src/test/resources/message-vectors.json
 * where the Android unit test picks them up.
 *
 * The Android test decrypts the reference message, re-derives the keys and
 * checks the safety number; it then seals its own message into
 * app/build/kotlin-sealed.json, which scripts/verify-sealed.ts opens with the
 * reference implementation. Together that proves the two implementations agree
 * byte for byte in both directions.
 *
 * Run:  bun run scripts/test-vectors.ts
 */
import { mkdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import {
  generateIdentity,
  openMessage,
  safetyNumber,
  sealMessage,
  type Identity,
} from "./client-crypto";

const b64 = (bytes: Uint8Array): string => Buffer.from(bytes).toString("base64");

/**
 * PKCS#8 DER for X25519/Ed25519 private keys is a fixed 16-byte prefix followed
 * by the raw 32-byte seed, so the seed can be moved between implementations as
 * plain base64.
 */
async function seed(key: CryptoKey): Promise<string> {
  const der = new Uint8Array(await crypto.subtle.exportKey("pkcs8", key));
  return b64(der.slice(der.length - 32));
}

const OUT = resolve(import.meta.dir, "../../app/src/test/resources/message-vectors.json");

const CONVERSATION = "conv-vector-0001";
const MESSAGE = "msg-vector-0001";
const PLAINTEXT = "Grüße aus der Referenz-Implementierung 🔐";

async function main() {
  const alice = await generateIdentity();
  const bob = await generateIdentity();
  const carol = await generateIdentity();

  const devices = [
    { deviceId: "device-bob", identityPublic: bob.identityPublic },
    { deviceId: "device-carol", identityPublic: carol.identityPublic },
  ];

  const sealed = await sealMessage(alice, CONVERSATION, MESSAGE, PLAINTEXT, devices);

  // Sanity: the reference implementation can open its own message again.
  const reopened = await openMessage({
    identity: bob,
    myDeviceId: "device-bob",
    conversationId: CONVERSATION,
    messageId: MESSAGE,
    senderIdentityPublic: alice.identityPublic,
    senderSigningPublic: alice.signingPublic,
    body: sealed.body,
    envelope: sealed.envelopes[0]!.wrappedKey,
  });
  if (reopened !== PLAINTEXT) throw new Error("reference implementation is not self-consistent");

  const vectors = {
    note: "Generated by server/scripts/test-vectors.ts - do not edit by hand.",
    conversationId: CONVERSATION,
    messageId: MESSAGE,
    plaintext: PLAINTEXT,
    sender: {
      name: "alice",
      deviceId: "device-alice",
      identityPublic: alice.identityPublic,
      signingPublic: alice.signingPublic,
      identitySeed: await seed(alice.identityPrivate),
      signingSeed: await seed(alice.signingPrivate),
    },
    recipients: [
      {
        name: "bob",
        deviceId: "device-bob",
        identityPublic: bob.identityPublic,
        signingPublic: bob.signingPublic,
        identitySeed: await seed(bob.identityPrivate),
        signingSeed: await seed(bob.signingPrivate),
      },
      {
        name: "carol",
        deviceId: "device-carol",
        identityPublic: carol.identityPublic,
        signingPublic: carol.signingPublic,
        identitySeed: await seed(carol.identityPrivate),
        signingSeed: await seed(carol.signingPrivate),
      },
    ],
    sealed,
    safetyNumber: await safetyNumber(alice, bob),
  };

  await mkdir(dirname(OUT), { recursive: true });
  await writeFile(OUT, `${JSON.stringify(vectors, null, 2)}\n`);
  console.log(`wrote ${OUT}`);
  console.log(`safety number: ${vectors.safetyNumber}`);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
